/**
 * 获取宫位详情
 * @param {Object} palace - 宫位数据 { shen, xing, men, gan, zhi, palace }
 * @returns {Array} 详情数组
 */
function getPalaceDetail(palace) {
  const details = [];

  if (palace.shen && KNOWLEDGE.shen[palace.shen]) {
    details.push({ type: '八神', name: palace.shen, ...KNOWLEDGE.shen[palace.shen] });
  }
  if (palace.xing && KNOWLEDGE.xing[palace.xing]) {
    details.push({ type: '九星', name: palace.xing, ...KNOWLEDGE.xing[palace.xing] });
  }
  if (palace.men && KNOWLEDGE.men[palace.men]) {
    details.push({ type: '八门', name: palace.men, ...KNOWLEDGE.men[palace.men] });
  }

  return details;
}

/**
 * 计算五行生克关系
 * @param {string} wuxing1 - 五行1
 * @param {string} wuxing2 - 五行2
 * @returns {string} 关系: '生' | '克' | '被生' | '被克' | '比和'
 */
function getWuxingRelation(wuxing1, wuxing2) {
  if (wuxing1 === wuxing2) return '比和';
  if (KNOWLEDGE.wuxingRelation.generate[wuxing1] === wuxing2) return '生';
  if (KNOWLEDGE.wuxingRelation.control[wuxing1] === wuxing2) return '克';
  if (KNOWLEDGE.wuxingRelation.generate[wuxing2] === wuxing1) return '被生';
  if (KNOWLEDGE.wuxingRelation.control[wuxing2] === wuxing1) return '被克';
  return '未知';
}

